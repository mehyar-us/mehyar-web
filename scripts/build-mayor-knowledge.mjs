// Build from rendered public content only; no API, private routes or user data.
import { readFileSync,writeFileSync } from 'node:fs';
import { createServer } from 'vite';
const server=await createServer({server:{middlewareMode:true},appType:'custom'});
try {
  const {publicPaths,resolveMeta}=await server.ssrLoadModule('/src/data/site-seo.ts');
  const decode=s=>s.replace(/&#x([\da-f]+);/gi,(_,n)=>String.fromCodePoint(parseInt(n,16))).replace(/&#(\d+);/g,(_,n)=>String.fromCodePoint(Number(n))).replaceAll('&amp;','&').replaceAll('&quot;','"').replaceAll('&apos;',"'").replaceAll('&lt;','<').replaceAll('&gt;','>');
  const pages=publicPaths.map(path=>{
    const html=readFileSync(path==='/'?'dist/public/index.html':`dist/public${path}/index.html`,'utf8'), main=html.match(/<main[^>]*>([\s\S]*?)<\/main>/)?.[1]||'';
    const text=decode(main.replace(/<script[\s\S]*?<\/script>/g,'').replace(/<\/[^>]+>/g,'\n').replace(/<[^>]*>/g,' ')).replace(/[ \t]+/g,' ').replace(/\n\s*\n/g,'\n').trim();
    const meta=resolveMeta(path);return {path,title:meta.title.replace(/ \| MehyarSoft$/,''),description:meta.description,text:text.slice(0,18000)};
  });
  writeFileSync('functions/api/_shared/mayorSiteKnowledge.js',`// Generated by scripts/build-mayor-knowledge.mjs from public route shells.\nexport const mayorPages = ${JSON.stringify(pages,null,2)};\n`);
  console.log(`Built Mayor knowledge for ${pages.length} public pages from current rendered copy.`);
} finally {await server.close();}
